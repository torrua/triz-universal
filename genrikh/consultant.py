from typing import Dict, List, Optional
from datetime import datetime
from pydantic import BaseModel
from genrikh.core import DualLoopResult
from genrikh.engine import OpenSourceAIEngine

class ClientProject(BaseModel):
    client_name: str
    project_title: str
    domain: str
    problem_statement: str
    target_metric: str
    constraint_metric: str

TEMPLATES: Dict[str, ClientProject] = {
    "freelancer_offline_sync": ClientProject(
        client_name="LocalCraft Freelance Services",
        project_title="Offline-First Mobile Invoicing Sync",
        domain="Mobile & Web SaaS",
        problem_statement=(
            "Freelancers in the field need instant invoice and receipt editing without network latency, "
            "but multi-device synchronization causes data merge conflicts and requires expensive distributed lock servers."
        ),
        target_metric="Instant Offline UX & Zero Sync Latency",
        constraint_metric="Zero Data Loss & Zero Cloud Lock Server Costs"
    ),
    "solo_founder_scale": ClientProject(
        client_name="Bootstrapped Micro-SaaS",
        project_title="10k RPS Zero-Cloud Scaling",
        domain="Cloud Architecture & Databases",
        problem_statement=(
            "A solo founder needs to handle sudden viral traffic spikes (up to 10k requests/sec) "
            "but cannot afford multi-region RDS clusters or enterprise Redis tiers costing thousands per month."
        ),
        target_metric="10,000 Requests/Sec Peak Throughput",
        constraint_metric="Strict $20/month Total Infrastructure Budget"
    ),
    "iot_wearable_battery": ClientProject(
        client_name="BioSense Wearables",
        project_title="Continuous Telemetry vs Coin-Cell Battery",
        domain="Hardware & Embedded Systems",
        problem_statement=(
            "A medical wearable requires continuous 1Hz sensor telemetry for clinical safety, "
            "but the 220mAh coin-cell battery drains in under 8 hours with active BLE transmission."
        ),
        target_metric="Continuous Real-time Patient Anomaly Detection",
        constraint_metric="30-Day Battery Life on a Single CR2032 Battery"
    )
}

class ConsultingReport:
    def __init__(self, project: ClientProject, result: DualLoopResult):
        self.project = project
        self.result = result
        self.generated_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    def to_markdown(self) -> str:
        p = self.project
        r = self.result
        lock = r.state_lock

        md = f"""# 🏛️ TRIZ Inventive Audit & Architectural Roadmap
**Client:** {p.client_name}  
**Project:** {p.project_title} ({p.domain})  
**Audit Date:** {self.generated_at}  
**Security & Privacy:** 🔒 *Audited 100% locally with Open-Source AI. Zero data was transmitted to third-party servers.*  

---

## 1. Executive Summary (Layer 1 — Non-Technical Overview)
> **Core Value:** Solving the core bottleneck without compromising on budget, reliability, or user experience.

{r.layer_1}

---

## 2. Problem Diagnosis & Contradiction Mapping
* **Improving Parameter (Goal):** {p.target_metric}
* **Worsening Parameter (Hard Constraint):** {p.constraint_metric}

### ⚡ The Physical Contradiction
> **{lock.physical_contradiction.to_statement()}**

---

## 3. Methodological TRIZ Passport (Layer 2 — Engineering Deep-Dive)
{r.layer_2}

---

## 4. Latent Resource Ledger (VPR — Zero Added Cost)
TRIZ mandates using internal and supersystem resources before purchasing new tools.
The following resources were mobilized to deliver this solution with $0 marginal cost:

| Resource Name | Domain | Availability | Marginal Cost |
|---|---|---|---|
"""
        for v in lock.mobilized_vpr:
            md += f"| **{v.name}** | {v.domain} | {v.availability} | {v.cost} |\n"

        md += f"""
---

## 5. Verification & Risk Mitigation
* **Verification Experiment:** {lock.verification_plan.experiment}
* **Baseline to Beat:** {lock.verification_plan.baseline}
* **Acceptance Threshold:** {lock.verification_plan.success_threshold}
* **Residual Risks to Monitor:**
"""
        for risk in r.residual_risks:
            md += f"  - ⚠️ {risk}\n"

        md += f"""
---
*Generated by [TRIZ Universal](https://github.com/torrua/triz-universal) — Open-Source AI Architecture Consultant.*
"""
        return md


class ConsultantSession:
    def __init__(self, engine: Optional[OpenSourceAIEngine] = None):
        self.engine = engine or OpenSourceAIEngine()

    def run_template(self, template_key: str) -> ConsultingReport:
        if template_key not in TEMPLATES:
            raise ValueError(f"Template '{template_key}' not found. Available: {list(TEMPLATES.keys())}")
        project = TEMPLATES[template_key]
        return self.audit(project)

    def audit(self, project: ClientProject) -> ConsultingReport:
        result = self.engine.solve(
            problem=project.problem_statement,
            param_a=project.target_metric,
            param_b=project.constraint_metric
        )
        return ConsultingReport(project, result)
